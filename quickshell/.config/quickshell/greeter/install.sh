#!/bin/sh
# Installs the Quickshell login screen for greetd. Does NOT switch your login manager:
# ly stays active until you enable greetd yourself.
set -e
G="$HOME/.config/quickshell/greeter"

echo "==> greetd"
sudo pacman -S --needed greetd

echo "==> theme folder (wallpaper + colours the greeter can read)"
sudo install -d -o "$USER" -g "$(id -gn)" -m 755 /var/lib/qs-greeter
sh "$G/sync.sh"

echo "==> greeter files -> /etc/greetd/greeter"
sudo install -d -m 755 /etc/greetd/greeter
sudo install -m 644 "$G/shell.qml" /etc/greetd/greeter/shell.qml
sudo ln -sfn /var/lib/qs-greeter/Colours.qml /etc/greetd/greeter/Colours.qml

echo "==> mini Hyprland for the login screen -> /etc/greetd/hyprland.lua"
{
	echo "-- Minimal Hyprland that only runs the Quickshell login screen (generated by install.sh)"
	grep '^hl.monitor' "$HOME/.config/hypr/hyprmon.lua" 2>/dev/null || true
	cat "$G/greeter-hyprland.lua"
} | sudo tee /etc/greetd/hyprland.lua >/dev/null

echo "==> greetd config (original kept as config.toml.orig)"
[ -f /etc/greetd/config.toml ] && [ ! -f /etc/greetd/config.toml.orig ] && sudo cp /etc/greetd/config.toml /etc/greetd/config.toml.orig
sudo install -m 644 "$G/greetd-config.toml" /etc/greetd/config.toml

echo "==> keep the login screen in sync with your wallpaper"
systemctl --user link "$G/systemd/greeter-sync.service"
systemctl --user enable --now "$G/systemd/greeter-sync.path"

echo "==> checks"
if fc-list | grep -qiE '^/usr/share/fonts/.*JetBrainsMono'; then echo "font: OK"
else echo "font: JetBrainsMono Nerd Font is not installed system-wide -> sudo pacman -S ttf-jetbrains-mono-nerd"; fi
ls -l /var/lib/qs-greeter
echo
echo "Installed. ly is still your login screen until you switch."
